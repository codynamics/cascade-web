"""CAS-1556: build qa/RELEASE-CHECKLIST.md from qa/cases/*.yaml, grouped by part.

    python qa/build_checklist.py           write the file
    python qa/build_checklist.py --check   exit 1 if the committed file differs from a fresh build

Reads the same YAML subset as tests/lint/qa-drift.mjs (list of maps; scalar or list-of-scalar values), so it
needs no PyYAML. The output is deterministic: no timestamps, cases sorted by (area file, id).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CASES_DIR = os.path.join(ROOT, "qa", "cases")
OUT = os.path.join(ROOT, "qa", "RELEASE-CHECKLIST.md")
PARTS = ("A", "B", "C", "D", "PROD")
PART_TITLES = {
    "A": "Part A",
    "B": "Part B",
    "C": "Part C",
    "D": "Part D",
    "PROD": "Post-production check",
}
HOW_AUTOMATED = {"unit", "browser", "agent-suite", "journey", "firstdays", "sql"}


def _scalar(s):
    s = s.strip()
    if s.startswith('"'):
        return json.loads(s)
    if s.startswith("'"):
        return s[1:-1].replace("''", "'")
    return s


def parse_cases(text, name="?"):
    cases, cur, list_key = [], None, None
    for i, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.strip().startswith("#"):
            continue
        m = re.match(r"^- (\w+):\s*(.*)$", raw)
        if m:
            cur = {"_file": name}
            cases.append(cur)
            list_key = None
            cur[m.group(1)] = _scalar(m.group(2))
            continue
        m = re.match(r"^  (\w+):\s*(.*)$", raw)
        if m and cur is not None:
            if m.group(2) == "":
                cur[m.group(1)] = []
                list_key = m.group(1)
            else:
                cur[m.group(1)] = _scalar(m.group(2))
                list_key = None
            continue
        m = re.match(r"^    - (.*)$", raw)
        if m and cur is not None and list_key:
            cur[list_key].append(_scalar(m.group(1)))
            continue
        raise ValueError(f"{name}:{i}: cannot parse case line: {raw}")
    return cases


def load_cases(cases_dir=CASES_DIR):
    out = []
    for f in sorted(os.listdir(cases_dir)):
        if f.endswith(".yaml"):
            with open(os.path.join(cases_dir, f), encoding="utf-8") as fh:
                out.extend(parse_cases(fh.read(), f))
    return out


def render(cases):
    lines = [
        "# Release QA checklist",
        "",
        "<!-- Generated by qa/build_checklist.py from qa/cases/*.yaml. Do not edit by hand: edit the cases,",
        "     then run `python qa/build_checklist.py`. The push gate (tests/lint/qa-drift.mjs) fails if this",
        "     file is stale. -->",
        "",
        f"{len(cases)} cases. `how` says what runs the check; `lee-phone` and `claude` are manual steps.",
        "",
    ]
    for part in PARTS:
        group = [c for c in cases if c.get("part") == part]
        if not group:
            continue
        lines += [f"## {PART_TITLES[part]}", ""]
        for c in sorted(group, key=lambda c: (c["_file"], c.get("id", ""))):
            auto = "auto" if c.get("how") in HOW_AUTOMATED else "manual"
            lines.append(f"- [ ] **{c['id']}** {c['title']} _({c['how']}, {auto})_")
            for e in c.get("expect", []):
                lines.append(f"  - {e}")
        lines.append("")
    other = [c for c in cases if c.get("part") not in PARTS]
    if other:
        lines += ["## Unassigned part", ""]
        for c in other:
            lines.append(f"- [ ] **{c.get('id')}** {c.get('title')} (part {c.get('part')!r})")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    text = render(load_cases())
    if "--check" in argv:
        have = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8", newline="") as fh:
                have = fh.read()
        if have.replace("\r\n", "\n") != text:
            print("qa/RELEASE-CHECKLIST.md is stale: run `python qa/build_checklist.py` and commit it.")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
