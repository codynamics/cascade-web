// CAS-960 AC: "With prefers-reduced-motion: reduce, no element on those surfaces reports a non-none
// animationName." emulateMedia's reduced-motion covers the whole browsing context, same as a real device
// setting — no per-element opt-in needed on this app's side beyond the @media queries it already ships.
test.describe("reduced motion (CAS-960 AC7)", () => {
  test.use({ reducedMotion: "reduce" });

  async function assertNoAnimation(page, surfaceName) {
    const animating = await page.evaluate(() => {
      const bad = [];
      document.querySelectorAll("body *").forEach(el => {
        // Only elements actually on screen — the app keeps every other .uscreen (Account, Languages, the
        // rest of the menu) in the DOM at display:none, and this check must be about the open surface,
        // not every screen the app happens to carry.
        if (el.offsetParent === null && el !== document.body) return;
        const style = getComputedStyle(el);
        if (style.visibility === "hidden" || style.display === "none") return;
        const name = style.animationName;
        if (name && name !== "none") bad.push(`${el.className || el.tagName}:${name}`);
      });
      return bad.slice(0, 10);
    });
    expect(animating, `${surfaceName}: animated elements — ${animating.join(", ")}`).toEqual([]);
  }

  test("onboarding honours reduced motion", async ({ page }) => {
    await freshApp(page);
    await expect(page.locator("#splashCta")).toBeVisible();
    await assertNoAnimation(page, "onboarding — splash");
    await page.locator("#splashCta").click();
    await expect(page.locator(".obhd")).toContainText("Let's get you set up.");
    await assertNoAnimation(page, "onboarding — v2_about step");
  });

  test("Watch, the film card, Agents and Moving honour reduced motion", async ({ page }) => {
    await reachListing(page);
    await assertNoAnimation(page, "Watch listing");

    const card = page.locator("#groups .card").first();
    await card.locator(".title").click();
    await expect(card).toHaveClass(/expanded/);
    await assertNoAnimation(page, "the film card (expanded)");

    await openAgentsScreenFromNav(page);
    await expect(page.locator("#agentsScreen")).toHaveClass(/open/);
    await assertNoAnimation(page, "Agents");

    await page.locator("#movingBtn").click();
    await expect(page.locator("#movingScreen")).toHaveClass(/open/);
    await assertNoAnimation(page, "Moving");
  });
});
