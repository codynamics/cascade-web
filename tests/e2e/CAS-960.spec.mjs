// CAS-960: the on-demand accessibility scan the ticket asks for — axe-core over the five highest-traffic
// surfaces (onboarding, Watch, Agents, Moving, the film card) at 390x844 (this suite's "ios" project is
// already that viewport, CAS-162/200), plus the role/state, Dynamic Type and reduced-motion checks the
// ticket's own acceptance criteria name. NOT part of `qa` — run on demand with `npm run test:a11y`, same
// shape as `test:agents` (CAS-794). Explicitly asked for by the ticket text, so this is the one exception
// CC_AUTONOMY's "don't write a Playwright spec for your ticket" rule itself carves out.
import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { appendFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { freshApp, toShortlist, finishFlow, toListing, openAgentsScreenFromNav } from "./helpers.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPORT_PATH = path.join(__dirname, "..", "..", "qa-a11y-report.txt");

const SERIOUS = new Set(["serious", "critical"]);

// File-level hook (outside every describe) so it runs exactly once before anything else in this spec,
// same clear-then-append shape as run-agent-suite.mjs's own qa-agents-report.txt handling.
test.beforeAll(() => {
  writeFileSync(REPORT_PATH,
    "CAS-960 accessibility report — axe scan, button names, contrast. Regenerated by `npm run test:a11y`.\n");
});

async function scanSurface(page, name, includeSelector) {
  let builder = new AxeBuilder({ page });
  if (includeSelector) builder = builder.include(includeSelector);
  const results = await builder.analyze();
  const serious = results.violations.filter(v => SERIOUS.has(v.impact));
  const lines = [`\n=== axe scan: ${name} ===`,
    `${results.violations.length} total violation(s), ${serious.length} serious/critical`];
  for (const v of results.violations) {
    lines.push(`  [${v.impact}] ${v.id}: ${v.help} (${v.nodes.length} node(s))`);
    for (const n of v.nodes.slice(0, 5)) lines.push(`    - ${n.target.join(" ")}`);
  }
  appendFileSync(REPORT_PATH, lines.join("\n") + "\n");
  return { all: results.violations, serious };
}

async function reachListing(page) {
  await toShortlist(page, "cinema");
  await finishFlow(page);
  await toListing(page);
}

test.describe("CAS-960 axe scan — zero serious/critical on the five named surfaces", () => {
  test("onboarding — splash", async ({ page }) => {
    await freshApp(page);
    await expect(page.locator("#splashCta")).toBeVisible();
    const { serious } = await scanSurface(page, "onboarding — splash");
    expect(serious.map(v => v.id)).toEqual([]);
  });

  test("onboarding — first step", async ({ page }) => {
    await freshApp(page);
    await page.locator("#splashCta").click();
    await expect(page.locator(".obhd")).toContainText("Let's get you set up.");
    const { serious } = await scanSurface(page, "onboarding — v2_about step");
    expect(serious.map(v => v.id)).toEqual([]);
  });

  test("Watch listing", async ({ page }) => {
    await reachListing(page);
    const { serious } = await scanSurface(page, "Watch listing");
    expect(serious.map(v => v.id)).toEqual([]);
  });

  test("the film card, expanded", async ({ page }) => {
    await reachListing(page);
    const card = page.locator("#groups .card").first();
    await expect(card).toBeVisible();
    await card.locator(".title").click();
    await expect(card).toHaveClass(/expanded/);
    const { serious } = await scanSurface(page, "the film card (expanded)");
    expect(serious.map(v => v.id)).toEqual([]);
  });

  test("Agents", async ({ page }) => {
    await reachListing(page);
    await openAgentsScreenFromNav(page);
    await expect(page.locator("#agentsScreen")).toHaveClass(/open/);
    // Scoped to #agentsScreen: it's a full-screen overlay (display:flex) sitting on top of the Watch
    // listing, which stays in the DOM underneath (covered, not display:none) — an unscoped scan would
    // also pick up Watch's own nodes and double-report anything already caught by the Watch listing test.
    const { serious } = await scanSurface(page, "Agents", "#agentsScreen");
    expect(serious.map(v => v.id)).toEqual([]);
  });

  test("Moving", async ({ page }) => {
    await reachListing(page);
    await page.locator("#movingBtn").click();
    await expect(page.locator("#movingScreen")).toHaveClass(/open/);
    const { serious } = await scanSurface(page, "Moving", "#movingScreen");
    expect(serious.map(v => v.id)).toEqual([]);
  });
});

// CAS-960 AC: "every element with role=radio, role=switch or class chip that can be selected also carries
// the matching aria-checked or aria-pressed, and the value changes when it is toggled" — a concrete
// round-trip on two real controls from the Watch mood sheet (a role=switch div and an aria-pressed
// chip button), not a blind DOM-wide click sweep (this app has disabled/decorative chips too — see
// renderMoodSheetBody's alsoShowHTML "always" chip — that a generic sweep would misfire on).
test("switches and pressed chips announce and update their state (CAS-960 AC4)", async ({ page }) => {
  await reachListing(page);
  // CAS-1247: the Filters button/badge are gone — the selected mood's own chip opens the sheet now.
  await page.locator(".moodchip.on").click();
  await expect(page.locator("#watchSheet")).toHaveClass(/open/);

  const sw = page.locator("#watchMineOnlySwitch");
  await expect(sw).toHaveAttribute("role", "switch");
  const swBefore = await sw.getAttribute("aria-checked");
  expect(["true", "false"]).toContain(swBefore);
  await sw.click();
  await expect(sw).toHaveAttribute("aria-checked", swBefore === "true" ? "false" : "true");

  const chip = page.locator("#watchSheetBody .chip:not([disabled])").first();
  const chipBefore = await chip.getAttribute("aria-pressed");
  expect(["true", "false"]).toContain(chipBefore);
  await chip.click();
  await expect(chip).toHaveAttribute("aria-pressed", chipBefore === "true" ? "false" : "true");
});

